export const assistantPrompts=[
 'На каких направлениях ожидается пиковая отгрузка?',
 'Что изменилось за два часа?',
 'Какие маршруты требуют внимания?',
 'Какие направления сильнее всего вырастут?',
 'Где ожидается снижение отгрузок?',
 'В какое время будет максимальная нагрузка?',
 'Покажи направления с самым большим прогнозом',
 'Как изменится прогноз в ближайшие два часа?',
 'Какие направления наиболее стабильны?',
 'На каких маршрутах ожидается резкий рост?'
]
export function samplePrompts(random:()=>number=Math.random):string[]{
 const pool=[...assistantPrompts]
 for(let i=pool.length-1;i>0;i--){const j=Math.floor(random()*(i+1));[pool[i],pool[j]]=[pool[j],pool[i]]}
 return pool.slice(0,3)
}
